-- Machine-readable source mappings are part of the criterion's approval.
ALTER TABLE app.award_criteria_versions
  ADD COLUMN source_rules JSONB,
  ADD COLUMN source_rules_revision INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN source_rules_by BIGINT REFERENCES app.users(user_id) ON DELETE SET NULL;

CREATE TABLE app.criteria_source_rule_history (
  history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  criteria_version_id BIGINT NOT NULL REFERENCES app.award_criteria_versions(criteria_version_id),
  revision INTEGER NOT NULL,
  previous_rules JSONB,
  source_rules JSONB,
  changed_by BIGINT REFERENCES app.users(user_id) ON DELETE SET NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
REVOKE ALL ON app.criteria_source_rule_history FROM anon, authenticated;

CREATE FUNCTION app.track_criteria_source_rules() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.source_rules_revision := CASE WHEN NEW.source_rules IS NULL THEN 0 ELSE 1 END;
    IF NEW.source_rules IS NULL THEN RETURN NEW; END IF;
  ELSE
    IF NEW.source_rules IS NOT DISTINCT FROM OLD.source_rules THEN
      NEW.source_rules_revision := OLD.source_rules_revision;
      RETURN NEW;
    END IF;
    NEW.source_rules_revision := OLD.source_rules_revision + 1;
  END IF;
  NEW.is_confirmed := false;
  NEW.confirmed_by := NULL;
  NEW.confirmed_at := NULL;
  RETURN NEW;
END;
$$;
CREATE TRIGGER criteria_source_rules_before BEFORE INSERT OR UPDATE ON app.award_criteria_versions
  FOR EACH ROW EXECUTE FUNCTION app.track_criteria_source_rules();

CREATE FUNCTION app.audit_criteria_source_rules() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.source_rules IS NOT NULL THEN
      INSERT INTO app.criteria_source_rule_history(criteria_version_id, revision, source_rules, changed_by)
      VALUES (NEW.criteria_version_id, NEW.source_rules_revision, NEW.source_rules, NEW.source_rules_by);
    END IF;
  ELSIF NEW.source_rules IS DISTINCT FROM OLD.source_rules THEN
    INSERT INTO app.criteria_source_rule_history(criteria_version_id, revision, previous_rules, source_rules, changed_by)
    VALUES (NEW.criteria_version_id, NEW.source_rules_revision, OLD.source_rules, NEW.source_rules, NEW.source_rules_by);
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER criteria_source_rules_after AFTER INSERT OR UPDATE ON app.award_criteria_versions
  FOR EACH ROW EXECUTE FUNCTION app.audit_criteria_source_rules();
