-- 1. Bảng EvaluationRuns (Lưu trữ lịch sử các phiên đánh giá có cấu trúc & AI)
CREATE TABLE IF NOT EXISTS app.evaluation_runs (
    run_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    evaluation_type VARCHAR(50) NOT NULL CHECK (evaluation_type IN ('CRITERION_ASSESSMENT', 'KPI_VERIFICATION', 'BATCH_BENCHMARK')),
    subject_type VARCHAR(20) NOT NULL CHECK (subject_type IN ('LECTURER', 'UNIT')),
    subject_id BIGINT NOT NULL,
    achievement_id BIGINT NULL REFERENCES app.achievements(achievement_id) ON DELETE SET NULL,
    application_id BIGINT NULL REFERENCES app.award_applications(application_id) ON DELETE SET NULL,
    kpi_goal_id BIGINT NULL REFERENCES app.kpi_goals(goal_id) ON DELETE SET NULL,
    provider VARCHAR(50) NOT NULL DEFAULT 'mock',
    model VARCHAR(100) NOT NULL,
    is_mock BOOLEAN NOT NULL DEFAULT FALSE,
    overall_status VARCHAR(50) NOT NULL CHECK (overall_status IN ('COMPLETED', 'FLAGGED_UNCONFIRMED', 'FAILED')),
    overall_conclusion VARCHAR(50) NOT NULL CHECK (overall_conclusion IN ('ELIGIBLE', 'INELIGIBLE', 'NEEDS_HUMAN_REVIEW', 'SIMULATION_ONLY')),
    automatic_award_granted BOOLEAN NOT NULL DEFAULT FALSE CHECK (automatic_award_granted = FALSE),
    input_snapshot JSONB NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    prompt_tokens INT NOT NULL DEFAULT 0,
    completion_tokens INT NOT NULL DEFAULT 0,
    total_tokens INT NOT NULL DEFAULT 0,
    latency_ms INT NOT NULL DEFAULT 0,
    is_stale BOOLEAN NOT NULL DEFAULT FALSE,
    executed_by BIGINT NOT NULL REFERENCES app.users(user_id) ON DELETE RESTRICT,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_eval_runs_subject ON app.evaluation_runs (subject_type, subject_id);
CREATE INDEX IF NOT EXISTS idx_eval_runs_executed_by ON app.evaluation_runs (executed_by);
CREATE INDEX IF NOT EXISTS idx_eval_runs_created_at ON app.evaluation_runs (executed_at DESC);
CREATE INDEX IF NOT EXISTS idx_eval_runs_app_id ON app.evaluation_runs (application_id);

-- 2. Bảng EvaluationCriterionResults (Chi tiết đánh giá từng tiêu chí trong phiên)
CREATE TABLE IF NOT EXISTS app.evaluation_criterion_results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES app.evaluation_runs(run_id) ON DELETE CASCADE,
    criterion_id BIGINT NOT NULL REFERENCES app.award_criteria_versions(criteria_version_id) ON DELETE RESTRICT,
    criterion_code VARCHAR(50) NOT NULL,
    criterion_name VARCHAR(255) NOT NULL,
    is_confirmed_by_lhu BOOLEAN NOT NULL DEFAULT FALSE,
    is_simulation BOOLEAN NOT NULL DEFAULT FALSE,
    target_min NUMERIC(10, 2) NULL,
    actual_recorded NUMERIC(10, 2) NULL,
    unit_metric VARCHAR(50) NULL,
    is_satisfied VARCHAR(20) NOT NULL, -- 'true', 'false', 'UNCONFIRMED'
    distinct_years INT NULL,
    consecutive_years BOOLEAN NULL,
    legal_references JSONB NOT NULL DEFAULT '[]',
    ai_analysis TEXT NOT NULL,
    human_review_required BOOLEAN NOT NULL DEFAULT TRUE,
    warning_notice TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_eval_crit_results_run ON app.evaluation_criterion_results (run_id);
CREATE INDEX IF NOT EXISTS idx_eval_crit_results_criterion ON app.evaluation_criterion_results (criterion_id);

-- 3. Bảo vệ dữ liệu qua Data API - chỉ cho phép Backend truy cập
REVOKE ALL ON app.evaluation_runs, app.evaluation_criterion_results FROM anon, authenticated;
