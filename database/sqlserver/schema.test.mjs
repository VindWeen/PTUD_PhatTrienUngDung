import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const base = new URL('./', import.meta.url);
const schema=fs.readFileSync(new URL('migrations/001_final_schema.sql',base),'utf8');
const triggers=fs.readFileSync(new URL('migrations/002_integrity_triggers.sql',base),'utf8');
const seed=fs.readFileSync(new URL('seed.sql',base),'utf8');
const manifest=JSON.parse(fs.readFileSync(new URL('schema-manifest.json',base),'utf8'));
test('baseline has all 53 final tables and columns from all 31 archived migrations',()=>{
  assert.equal(manifest.sourceFiles.length,31);
  assert.equal(Object.keys(manifest.tables).length,53);
  const starts=[...schema.matchAll(/CREATE TABLE app\.(\w+)\s*\(/g)];
  assert.equal(starts.length,53);
  for(let i=0;i<starts.length;i++){
    const table=starts[i][1], block=schema.slice(starts[i].index,starts[i+1]?.index ?? schema.indexOf('ALTER TABLE'));
    for(const col of manifest.tables[table]) assert.match(block,new RegExp(`(?:\\n\\s+)\\[?${col}\\]?\\s`),`${table}.${col}`);
  }
});
test('native T-SQL has no surviving PostgreSQL executable syntax',()=>{
  const executable=schema.replace(/--[^\r\n]*/g,'');
  assert.doesNotMatch(executable,/\b(?:TIMESTAMPTZ|JSONB|BOOLEAN|UUID|RETURNING|ILIKE|EXCLUDE USING|GENERATED BY)\b|\$\d+|::|\b(?:BIGINT|REAL)\[\]/i);
  assert.equal((schema.match(/ISJSON\(/g)||[]).length,manifest.jsonColumns.length);
});
test('all baseline foreign keys point at existing columns, without duplicate relationships',()=>{
  const seen=new Set();
  for(const m of schema.matchAll(/ALTER TABLE app\.(\w+) ADD (?:CONSTRAINT \w+\s+)?FOREIGN KEY\s*\(([^)]+)\)\s+REFERENCES app\.(\w+)\s*\(([^)]+)\)/g)){
    for(const col of m[2].split(',')) assert.ok(manifest.tables[m[1]].includes(col.trim()),`${m[1]}.${col}`);
    for(const col of m[4].split(',')) assert.ok(manifest.tables[m[3]].includes(col.trim()),`${m[3]}.${col}`);
    const key=[m[1],m[2].replace(/\s/g,''),m[3],m[4].replace(/\s/g,'')].join(':');
    assert.ok(!seen.has(key),`duplicate foreign key ${key}`); seen.add(key);
  }
  assert.ok(seen.size>100);
});
test('dropped evidence schema index does not survive; application versions/handoff preserved',()=>{
  assert.doesNotMatch(schema,/ON app\.evidence_files\(achievement_id\)/);
  assert.match(schema,/PRIMARY KEY\(application_id,input_version\)/);
  assert.match(schema,/fk_award_record_application_input/);
  assert.match(schema,/uq_award_records_application_active/);
  assert.match(schema,/uq_kpi_results_achievement[\s\S]*WHERE achievement_id IS NOT NULL/);
});
test('database safeguards include set-based cycle, range, immutable input and source rule tracking',()=>{
  for(const name of ['trg_prevent_organization_cycle','trg_lecturer_assignments_no_overlap','trg_unit_representatives_no_overlap','immutable_award_application_input','criteria_source_rules_after']) assert.ok(triggers.includes(name));
  assert.match(triggers,/TABLOCKX,HOLDLOCK/);
  assert.match(triggers,/INSERT app\.criteria_source_rule_history/);
  assert.doesNotMatch(triggers,/ON app\.evidences/);
});
test('demo seed checks every application table and never deletes existing data',()=>{
  for(const table of Object.keys(manifest.tables)) assert.ok(seed.includes(`IF EXISTS(SELECT 1 FROM app.${table} WITH(TABLOCKX,HOLDLOCK))`),table);
  assert.doesNotMatch(seed.replace(/--[^\r\n]*/g,''),/\b(?:TRUNCATE|DELETE|DROP)\s/i);
  assert.ok(seed.includes("N'council.demo'"));
  assert.doesNotMatch(seed,/\b(?:NOW\(\)|TIMESTAMPTZ|OVERRIDING SYSTEM VALUE|INTERVAL|ALTER SEQUENCE)\b/);
});
